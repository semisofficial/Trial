DO $$
DECLARE guard record;
BEGIN
  FOR guard IN SELECT * FROM (VALUES
    ('inventory', 'inventory_stock_nonnegative', 'stock IS NULL OR stock >= 0'),
    ('inventory', 'inventory_price_nonnegative', 'selling_price IS NOT NULL AND selling_price >= 0'),
    ('orders', 'orders_status_allowed', 'status IS NOT NULL AND status IN (''pending'',''accepted'',''declined'',''completed'')'),
    ('orders', 'orders_payment_status_allowed', 'payment_status IS NOT NULL AND payment_status IN (''paid'',''unpaid'')'),
    ('orders', 'orders_total_nonnegative', 'total IS NOT NULL AND total >= 0'),
    ('menu_items', 'menu_items_quantities_positive', 'min_qty > 0 AND step_qty > 0'),
    ('menu_items', 'menu_items_price_nonnegative', 'default_price >= 0'),
    ('order_items', 'order_items_values_valid', 'quantity > 0 AND unit_price >= 0 AND subtotal >= 0')
  ) AS guards(table_name, constraint_name, predicate)
  LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid=guard.table_name::regclass AND conname=guard.constraint_name) THEN
      EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I CHECK (%s) NOT VALID', guard.table_name, guard.constraint_name, guard.predicate);
    END IF;
    EXECUTE format('ALTER TABLE %I VALIDATE CONSTRAINT %I', guard.table_name, guard.constraint_name);
  END LOOP;
END $$;
