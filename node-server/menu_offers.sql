CREATE TABLE IF NOT EXISTS categories (
  id text PRIMARY KEY
);
-- Older populated databases require a category name. Preserve their labels;
-- the minimal baseline used by earlier local installs has only an id column.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_attribute
    WHERE attrelid = 'categories'::regclass AND attname = 'name' AND NOT attisdropped
  ) THEN
    INSERT INTO categories(id, name) VALUES
      ('fried', 'Fried Snacks'), ('frozen', 'Frozen Snacks'), ('mains', 'Biriyani & Curries')
    ON CONFLICT (id) DO NOTHING;
  ELSE
    INSERT INTO categories(id) VALUES ('fried'), ('frozen'), ('mains')
    ON CONFLICT (id) DO NOTHING;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS menu_items (
  id text PRIMARY KEY,
  category_id text NOT NULL REFERENCES categories(id),
  name text NOT NULL,
  unit text NOT NULL DEFAULT '',
  min_qty numeric NOT NULL DEFAULT 1,
  step_qty numeric NOT NULL DEFAULT 1,
  seasonal boolean NOT NULL DEFAULT false,
  image text NOT NULL DEFAULT '',
  default_price numeric NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS inventory (
  menu_item_id text PRIMARY KEY REFERENCES menu_items(id),
  selling_price numeric NOT NULL,
  stock numeric,
  available boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  phone text NOT NULL,
  email text,
  address text,
  latitude numeric,
  longitude numeric
);

CREATE TABLE IF NOT EXISTS orders (
  id text PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers(id),
  invoice_id text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  order_mode text NOT NULL,
  notes text,
  total numeric NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  payment_status text NOT NULL DEFAULT 'unpaid',
  paymet text NOT NULL DEFAULT 'cod',
  archived boolean NOT NULL DEFAULT false,
  delivery_date date,
  delivery_slot text,
  stock_reserved boolean NOT NULL DEFAULT false,
  invoice_share_token text NOT NULL DEFAULT replace(gen_random_uuid()::text, '-', ''),
  synced_at timestamptz
);

CREATE TABLE IF NOT EXISTS order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id text NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  menu_item_id text NOT NULL REFERENCES menu_items(id),
  quantity numeric NOT NULL,
  unit_price numeric NOT NULL,
  subtotal numeric NOT NULL
);

CREATE TABLE IF NOT EXISTS sales_summary (
  summary_date date PRIMARY KEY,
  orders_count integer NOT NULL DEFAULT 0,
  revenue numeric NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS app_migrations (name text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());
