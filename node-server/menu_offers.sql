-- Link newly imported variants on EVERY run. Existing owners/manual counts
-- remain authoritative; only a completely new family gets a MAX opening count.
DO $$
DECLARE family record;
BEGIN
  FOR family IN
    WITH snacks AS (
      SELECT m.id, m.stock_group_id, i.stock, CASE
        WHEN lower(name) LIKE '%momo%' THEN 'momos'
        WHEN lower(name) LIKE '%kallumakaya%' THEN 'kallumakaya'
        ELSE regexp_replace(lower(name), '[^a-z0-9]', '', 'g') END AS family_name
      FROM menu_items m JOIN inventory i ON i.menu_item_id=m.id
      WHERE category_id IN ('fried', 'frozen') AND NOT retired
    ) SELECT array_agg(id) ids, COALESCE(MIN(stock_group_id), MIN(id)) owner,
        COUNT(DISTINCT stock_group_id) owner_count, FLOOR(MAX(COALESCE(stock, 0))) opening_stock
      FROM snacks GROUP BY family_name
  LOOP
    IF family.owner_count > 1 THEN
      RAISE EXCEPTION 'Conflicting shared stock owners for %. Review counts before merging.', family.ids;
    END IF;
    IF family.owner_count = 0 THEN
      UPDATE inventory SET stock=family.opening_stock WHERE menu_item_id=family.owner;
    END IF;
    UPDATE menu_items SET stock_group_id=family.owner
      WHERE id=ANY(family.ids) AND stock_group_id IS NULL;
  END LOOP;
  INSERT INTO app_migrations(name) VALUES ('shared-snack-stock-v1') ON CONFLICT DO NOTHING;
END $$;

CREATE TABLE IF NOT EXISTS offers (
  slug text PRIMARY KEY,
  title text NOT NULL CHECK (length(title) BETWEEN 1 AND 100),
  items jsonb NOT NULL CHECK (jsonb_typeof(items) = 'array'),
  starts_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT (now() + interval '24 hours'),
  closed boolean NOT NULL DEFAULT false,
  CHECK (expires_at > starts_at)
);
CREATE INDEX IF NOT EXISTS idx_offers_expiry ON offers(expires_at);

